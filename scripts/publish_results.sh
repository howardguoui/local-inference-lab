#!/usr/bin/env bash
# Run the benchmark matrix on this GPU machine and publish the results to GitHub.
#   scripts/publish_results.sh              # full matrix
#   OFFLOAD=1 scripts/publish_results.sh    # plus the 32B partial-offload run
#   SKIP_RUN=1 scripts/publish_results.sh   # just commit results already in results/
set -euo pipefail
cd "$(dirname "$0")/.."
if [ "${SKIP_RUN:-0}" != 1 ]; then
  scripts/run_matrix.sh
fi
inference-lab report >/dev/null
if [ -z "$(git status --porcelain results)" ]; then
  echo "No new results to publish."; exit 0
fi
GPU=$(inference-lab gpu | python -c "import json,sys; print(json.load(sys.stdin).get('name','GPU'))")
git add results
git commit -m "Benchmark results: $(date +%Y-%m-%d) on $GPU" -m "Generated by scripts/publish_results.sh from real runs."
git pull --rebase origin main
git push origin main
echo "Published. See results/latest.md on GitHub."
